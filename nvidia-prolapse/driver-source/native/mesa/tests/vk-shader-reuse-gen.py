#!/usr/bin/env python3
"""Generate the SPIR-V variants for vk-shader-reuse.c.

vk-shader-reuse-gen.py OUT_DIR  ->  OUT_DIR/vk-shader-reuse.spv.h

NV vertex shaders and NF fragment shaders, each an exact unrolled integer chain of a
different length (so every variant has a different code size and the shader heap places
the next pipeline's headers and code over the previous pipeline's ranges). The C test
computes the same chains on the CPU. Needs glslc on PATH.
"""
import os
import subprocess
import sys
import tempfile

NV = 8
NF = 12


def vs_len(k):
    return 3 + 29 * k


def fs_len(k):
    return 5 + 41 * k


def chain(var, n, salt):
    # x = (x ^ x >> 13) * 1664525 + c_i : the xorshift keeps NIR from folding the chain.
    lines = []
    for i in range(n):
        c = (i * 7919 + salt * 31 + 17) % 65521
        lines.append(f"   {var} = ({var} ^ ({var} >> 13u)) * 1664525u + {c}u;")
    return "\n".join(lines)


def vs_src(k):
    return f"""#version 450
layout(location = 0) flat out uint v_val;
void main() {{
   vec2 p = vec2(float((gl_VertexIndex << 1) & 2), float(gl_VertexIndex & 2));
   gl_Position = vec4(p * 2.0 - 1.0, 0.0, 1.0);
   uint x = uint(gl_VertexIndex) + {k + 1}u;
{chain('x', vs_len(k), 1000 + k)}
   v_val = x;
}}
"""


def fs_src(k):
    return f"""#version 450
layout(location = 0) flat in uint v_val;
layout(location = 0) out uint o;
void main() {{
   uint x = v_val + {k}u;
{chain('x', fs_len(k), 2000 + k)}
   o = x;
}}
"""


def compile_spv(src, stage, tmp):
    path = os.path.join(tmp, f"s.{stage}")
    with open(path, "w") as f:
        f.write(src)
    out = path + ".spv"
    subprocess.run(["glslc", "-O0", f"-fshader-stage={stage}", path, "-o", out], check=True)
    with open(out, "rb") as f:
        data = f.read()
    assert len(data) % 4 == 0
    return [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]


def main():
    out_dir = sys.argv[1]
    os.makedirs(out_dir, exist_ok=True)
    h = ["/* generated by vk-shader-reuse-gen.py */", "#include <stdint.h>",
         f"#define REUSE_NV {NV}", f"#define REUSE_NF {NF}"]
    with tempfile.TemporaryDirectory() as tmp:
        for kind, n, srcf, stage in (("vs", NV, vs_src, "vert"), ("fs", NF, fs_src, "frag")):
            for k in range(n):
                words = compile_spv(srcf(k), stage, tmp)
                h.append(f"static const uint32_t {kind}{k}[] = {{" +
                         ",".join(f"0x{w:08x}" for w in words) + "};")
            h.append(f"static const uint32_t *const {kind}_code[] = {{" +
                     ",".join(f"{kind}{k}" for k in range(n)) + "};")
            h.append(f"static const uint32_t {kind}_size[] = {{" +
                     ",".join(f"sizeof({kind}{k})" for k in range(n)) + "};")
    h.append("static const uint32_t vs_len[] = {" + ",".join(str(vs_len(k)) for k in range(NV)) + "};")
    h.append("static const uint32_t fs_len[] = {" + ",".join(str(fs_len(k)) for k in range(NF)) + "};")
    with open(os.path.join(out_dir, "vk-shader-reuse.spv.h"), "w") as f:
        f.write("\n".join(h) + "\n")


if __name__ == "__main__":
    main()
