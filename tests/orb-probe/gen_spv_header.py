#!/usr/bin/env python3
"""Turn compiled SPIR-V blobs into a C header with embedded arrays.

orb_probe.c links no external files, and xxd is not installed on this host,
so the arrays are generated here with python3 (stdlib only).

usage: gen_spv_header.py <spv-dir> <out-header>
"""
import os
import sys

SHADERS = ["dispatch_a", "prepare_args", "dispatch_b"]


def main() -> int:
    if len(sys.argv) != 3:
        sys.stderr.write(__doc__)
        return 2
    spv_dir, out_path = sys.argv[1], sys.argv[2]

    out = []
    out.append("/* generated by gen_spv_header.py -- do not edit */")
    out.append("#pragma once")
    out.append("")
    for name in SHADERS:
        p = os.path.join(spv_dir, name + ".spv")
        with open(p, "rb") as f:
            data = f.read()
        if len(data) % 4 != 0:
            sys.stderr.write("%s: size %d is not a multiple of 4\n" % (p, len(data)))
            return 1
        if len(data) < 20:
            sys.stderr.write("%s: too small to be SPIR-V\n" % p)
            return 1
        magic = int.from_bytes(data[0:4], "little")
        if magic != 0x07230203:
            sys.stderr.write("%s: bad SPIR-V magic 0x%08x\n" % (p, magic))
            return 1
        out.append("static const unsigned char orb_spv_%s[] = {" % name)
        line = "   "
        for b in data:
            chunk = " 0x%02x," % b
            if len(line) + len(chunk) > 100:
                out.append(line)
                line = "   "
            line += chunk
        if line.strip():
            out.append(line)
        out.append("};")
        out.append("static const unsigned int orb_spv_%s_len = %d;" % (name, len(data)))
        out.append("")
    with open(out_path, "w") as f:
        f.write("\n".join(out))
    sys.stderr.write("wrote %s (%d shaders)\n" % (out_path, len(SHADERS)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
